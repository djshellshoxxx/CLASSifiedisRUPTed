#!/usr/bin/env node
// Evidence-based feature status (project status tracking; complements tools/trace).
// Usage: node tools/status/status.mjs [--results vitest.json] [--write]
// Two independent, mechanically derived measures per module:
//   interface  = commands/queries named in module.spec.yaml that exist in non-test source
//   covered    = requirements with a mapped test ID that PASSED in the supplied results
// Neither measure is a judgement of quality or release readiness. Without --results,
// requirement coverage is reported as zero (source references never count as passing).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, FEATURES, featureOf, loadCatalog, loadSpecs } from '../specgen/model.mjs';
import { walk } from '../lib/walk.mjs';
import { trace } from '../trace/trace.mjs';

const DEFINITION = /define(?:Command|Query|Subscriber)\s*\(/g;
const NAME = /\bname:\s*['"]([a-z0-9_.]+)['"]/;
const MODULE = /\bmodule:\s*['"](F\d\d\.S\d\d\.M\d\d)['"]/;

/** Command/query/subscriber definitions in non-test source: [{ name, module, file }]. */
export function scanDefinitions(root = ROOT) {
  const found = [];
  for (const dir of ['packages', 'apps']) {
    const base = join(root, dir);
    if (!existsSync(base)) continue;
    for (const file of walk(base, (p) => /\.ts$/.test(p) && !/\.(test|spec)\.ts$/.test(p) && !/\/testing\//.test(p))) {
      const source = readFileSync(file, 'utf8');
      for (const match of source.matchAll(DEFINITION)) {
        // The definition header (name, module, capability) sits at the start of the object literal.
        const head = source.slice(match.index, match.index + 800);
        const name = NAME.exec(head)?.[1];
        const module = MODULE.exec(head)?.[1];
        if (name && module) found.push({ name, module, file: relative(root, file) });
      }
    }
  }
  return found;
}

const pct = (n, d) => (d ? `${((100 * n) / d).toFixed(1)}%` : 'n/a');

export function status({ resultPath = null, root = ROOT } = {}) {
  const specs = loadSpecs(loadCatalog());
  const { summary } = trace({ resultPath });
  const coverage = new Map(summary.map((s) => [s.id, s]));
  const definitions = scanDefinitions(root);
  const defined = new Set(definitions.map((d) => d.name));
  const modules = [];
  for (const [id, entry] of specs) {
    const cqe = entry.spec?.processes?.commands_queries_events ?? {};
    const declared = [...(cqe.commands ?? []), ...(cqe.queries ?? [])].map((x) => x.name);
    const implemented = declared.filter((name) => defined.has(name));
    const sources = [...new Set(definitions.filter((d) => d.module === id).map((d) => d.file))].sort();
    const codePath = join(root, entry.cat.code ?? '');
    const present = sources.length > 0 || (Boolean(entry.cat.code) && (existsSync(codePath) || existsSync(`${codePath}.ts`)));
    const runtime = declared.length
      ? (implemented.length === 0 ? (present ? 'partial' : 'none') : implemented.length === declared.length ? 'interface-complete' : 'partial')
      : (present ? 'present' : 'none');
    const cov = coverage.get(id) ?? { total: 0, covered: 0, title: entry.cat.title, scope: entry.spec?.scope ?? '?' };
    modules.push({ id, title: entry.cat.title, scope: cov.scope, runtime, declared: declared.length, implemented: implemented.length,
      missing: declared.filter((name) => !defined.has(name)), requirements: cov.total, covered: cov.covered, sources });
  }
  const features = Object.entries(FEATURES).map(([id, [slug, title]]) => {
    const mine = modules.filter((m) => featureOf(m.id) === id);
    const sum = (key) => mine.reduce((total, m) => total + m[key], 0);
    return { id, slug, title, modules: mine.length, withRuntime: mine.filter((m) => m.runtime !== 'none').length,
      withPassingTests: mine.filter((m) => m.covered > 0).length, declared: sum('declared'), implemented: sum('implemented'),
      requirements: sum('requirements'), covered: sum('covered') };
  });
  const total = (key) => features.reduce((n, f) => n + f[key], 0);
  const totals = { modules: total('modules'), withRuntime: total('withRuntime'), withPassingTests: total('withPassingTests'),
    declared: total('declared'), implemented: total('implemented'), requirements: total('requirements'), covered: total('covered') };
  return { modules, features, totals, executed: Boolean(resultPath) };
}

export function render({ modules, features, totals, executed }) {
  const lines = ['# Feature status (generated)', '',
    'Generated by `pnpm run status -- --results test-results/domain.json --write`. Do not edit by hand.', '',
    '- **Interface** counts commands and queries named in each `module.spec.yaml` that exist in non-test source.',
    '- **Requirements covered** counts specification requirements with a mapped test ID that passed in the supplied Vitest results.',
    '- Browser, CLI and load evidence is recorded separately; neither column measures quality or release readiness.',
    executed ? '' : '- **No execution results were supplied: requirement coverage below is zero by construction.**', '',
    `**Totals:** ${totals.withRuntime}/${totals.modules} modules have runtime code; interface ${totals.implemented}/${totals.declared} (${pct(totals.implemented, totals.declared)}); requirements covered ${totals.covered}/${totals.requirements} (${pct(totals.covered, totals.requirements)}).`, '',
    '## By feature', '', '| Feature | Modules with runtime | Modules with passing mapped tests | Interface | Requirements covered |', '|---|---|---|---|---|',
    ...features.map((f) => `| ${f.id} ${f.title} | ${f.withRuntime}/${f.modules} | ${f.withPassingTests}/${f.modules} | ${f.implemented}/${f.declared} (${pct(f.implemented, f.declared)}) | ${f.covered}/${f.requirements} (${pct(f.covered, f.requirements)}) |`), '',
    '## By module', '', '| Module | Title | Runtime | Interface | Requirements covered |', '|---|---|---|---|---|',
    ...modules.map((m) => `| ${m.id} | ${m.title} | ${m.runtime} | ${m.implemented}/${m.declared} | ${m.covered}/${m.requirements} |`)];
  return lines.filter((line, i, all) => !(line === '' && all[i - 1] === '')).join('\n') + '\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  const at = args.indexOf('--results');
  const resultPath = at >= 0 ? args[at + 1] : null;
  if (at >= 0 && (!resultPath || resultPath.startsWith('--'))) throw new Error('--results requires a JSON file path');
  const report = status({ resultPath });
  const t = report.totals;
  console.log(`modules with runtime: ${t.withRuntime}/${t.modules}; interface: ${t.implemented}/${t.declared}; requirements covered: ${t.covered}/${t.requirements}`);
  if (args.includes('--write')) {
    mkdirSync(join(ROOT, 'docs', 'status'), { recursive: true });
    writeFileSync(join(ROOT, 'docs', 'status', 'FEATURE_STATUS.md'), render(report));
    writeFileSync(join(ROOT, 'docs', 'status', 'feature-status.json'), JSON.stringify({ totals: report.totals, features: report.features, modules: report.modules }, null, 2) + '\n');
  }
}
