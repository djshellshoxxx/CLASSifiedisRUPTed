#!/usr/bin/env node
// Requirement → test traceability (CTR-TST-001 TST-1/TST-4).
// Usage: node tools/trace/trace.mjs [--strict] [--results vitest.json] [--write]
//  --results  vitest JSON reporter output; only passing tests count as coverage.
//  --write    writes planning/TRACEABILITY.md.
//  --strict   exit 1 when any MVP requirement of an implemented module lacks a passing test.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { ROOT, PROCESSES, loadCatalog, loadSpecs, cells, reqId } from '../specgen/model.mjs';
import { walk } from '../lib/walk.mjs';

const args = process.argv.slice(2);
const opt = (f) => args.includes(f);
const resultsFile = args.includes('--results') ? args[args.indexOf('--results') + 1] : null;
const TEST_ID = /TEST-PS-(\d{3})-09\.T(\d\d)/g;

/** Finds test IDs referenced in test source files: Map testId -> Set(files). */
export function scanTestSources() {
  const files = walk(ROOT, (p) => /\.(test|spec)\.(ts|mts|js|mjs)$/.test(p));
  const found = new Map();
  for (const f of files) {
    const src = readFileSync(f, 'utf8');
    for (const m of src.matchAll(TEST_ID)) {
      const id = m[0];
      if (!found.has(id)) found.set(id, new Set());
      found.get(id).add(relative(ROOT, f));
    }
  }
  return found;
}

/** Reads vitest JSON results: Map testId -> 'passed'|'failed' (any failure wins). */
export function readResults(file) {
  const status = new Map();
  if (!file || !existsSync(file)) return null;
  const json = JSON.parse(readFileSync(file, 'utf8'));
  for (const suite of json.testResults || []) {
    for (const t of suite.assertionResults || []) {
      for (const m of String(t.fullName || t.title).matchAll(TEST_ID)) {
        // Any failing assertion for an ID marks it failed; otherwise passed.
        if (t.status !== 'passed') status.set(m[0], 'failed');
        else if (!status.has(m[0])) status.set(m[0], 'passed');
      }
    }
  }
  return status;
}

export function trace() {
  const catalog = loadCatalog();
  const specs = loadSpecs(catalog);
  const found = scanTestSources();
  const results = readResults(resultsFile);
  const rows = []; const summary = [];
  for (const [id, e] of specs) {
    if (!e.spec) continue;
    const ps = e.cat.ps;
    const tests = (e.spec.processes.contract_and_acceptance_tests.tests || []).map(cells);
    const implemented = tests.some(([tid]) => found.has(`TEST-${ps}-09.${tid}`));
    let total = 0; let covered = 0;
    for (const [pp, key] of PROCESSES) {
      (e.spec.processes[key].requirements || []).forEach((_, i) => {
        total++;
        const local = `${pp}.R${String(i + 1).padStart(2, '0')}`;
        const mapped = tests.filter(([, , cov]) => cov.split(',').map((s) => s.trim()).includes(local)).map(([tid, level]) => ({ id: `TEST-${ps}-09.${tid}`, level }));
        const present = mapped.filter((t) => found.has(t.id) && (!results || results.get(t.id) === 'passed'));
        if (present.length) covered++;
        rows.push({ module: id, req: reqId(ps, pp, i), tests: mapped.map((t) => t.id), passing: present.map((t) => t.id), files: [...new Set(present.flatMap((t) => [...found.get(t.id)]))] });
      });
    }
    summary.push({ id, title: e.cat.title, scope: e.spec.scope, implemented, total, covered });
  }
  return { rows, summary, found, results };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { rows, summary } = trace();
  const impl = summary.filter((s) => s.implemented);
  const tot = summary.reduce((a, s) => a + s.total, 0); const cov = summary.reduce((a, s) => a + s.covered, 0);
  const gaps = rows.filter((r) => !r.passing.length && impl.some((s) => s.id === r.module && s.scope === 'MVP'));
  console.log(`modules with tests: ${impl.length}/${summary.length}; requirements covered: ${cov}/${tot}; gaps in implemented MVP modules: ${gaps.length}`);
  if (opt('--write')) {
    const md = ['# Requirements traceability', '', 'Generated by `pnpm trace --write`. Coverage counts a requirement when at least one mapped test ID appears in a test file' + (resultsFile ? ' and passed in the supplied results.' : '.'), '',
      '| Module | Title | Scope | Requirements covered |', '|---|---|---|---|',
      ...summary.map((s) => `| ${s.id} | ${s.title} | ${s.scope} | ${s.covered}/${s.total} |`), '', '## Uncovered requirements in implemented modules', '',
      ...(gaps.length ? gaps.map((g) => `- ${g.req} (${g.module}) expects ${g.tests.join(', ')}`) : ['_None._'])];
    writeFileSync(join(ROOT, 'planning', 'TRACEABILITY.md'), md.join('\n') + '\n');
  }
  if (opt('--strict') && gaps.length) { for (const g of gaps.slice(0, 50)) console.log(`GAP ${g.req} ${g.module}`); process.exit(1); }
}
