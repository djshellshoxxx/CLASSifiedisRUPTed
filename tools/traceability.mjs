#!/usr/bin/env node
// F17.S03.M02 gate: requirements(module) -> code -> test traceability.
// Reads INDEX.md (all 148 hierarchy modules) and every packages/*/traceability.json and
// apps/*/traceability.json; writes TRACEABILITY.md. With --check, fails if any module is
// unmapped, mapped twice, or references a missing file.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const check = process.argv.includes('--check');

const index = readFileSync(join(root, 'INDEX.md'), 'utf8');
const modules = [...index.matchAll(/\[(F\d{2}\.S\d{2}\.M\d{2}) (mod_[a-z0-9_]+)\]\(([^)]+)\/SPEC\.md\)/g)].map((m) => ({ id: m[1], name: m[2], path: m[3] }));

const entries = new Map();
const problems = [];
for (const base of ['packages', 'apps']) {
  for (const pkg of readdirSync(join(root, base))) {
    const file = join(root, base, pkg, 'traceability.json');
    if (!existsSync(file)) continue;
    let list;
    try {
      list = JSON.parse(readFileSync(file, 'utf8'));
    } catch (e) {
      problems.push(`${base}/${pkg}/traceability.json: invalid JSON (${e.message})`);
      continue;
    }
    for (const e of list) {
      if (entries.has(e.module)) problems.push(`${e.module}: mapped by both ${entries.get(e.module).owner} and ${base}/${pkg}`);
      entries.set(e.module, { ...e, owner: `${base}/${pkg}` });
      for (const f of [...(e.code ?? []), ...(e.tests ?? [])]) {
        if (!existsSync(join(root, f))) problems.push(`${e.module}: missing file ${f}`);
      }
      if (!['implemented', 'partial', 'deferred'].includes(e.status)) problems.push(`${e.module}: invalid status ${e.status}`);
      if (e.status === 'implemented' && (!(e.tests ?? []).length || !(e.code ?? []).length)) problems.push(`${e.module}: implemented without code and tests`);
    }
  }
}

const known = new Set(modules.map((m) => m.id));
for (const id of entries.keys()) if (!known.has(id)) problems.push(`${id}: not in INDEX.md`);
const unmapped = modules.filter((m) => !entries.has(m.id));
for (const m of unmapped) problems.push(`${m.id} (${m.path}): unmapped`);

const counts = { implemented: 0, partial: 0, deferred: 0 };
const rows = modules.map((m) => {
  const e = entries.get(m.id);
  if (!e) return `| ${m.id} | [${m.path}](${m.path}/SPEC.md) | — | — | — | **unmapped** |`;
  counts[e.status]++;
  const links = (fs) => (fs ?? []).map((f) => `[${f.split('/').pop()}](${f})`).join('<br>') || '—';
  return `| ${m.id} | [${m.path}](${m.path}/SPEC.md) | ${e.owner} | ${links(e.code)} | ${links(e.tests)} | ${e.status}${e.notes ? `: ${String(e.notes).replace(/\|/g, '/')}` : ''} |`;
});

const md = `# Requirements → code → test traceability

Generated by \`node tools/traceability.mjs\`; do not edit by hand.

Modules: ${modules.length} · implemented ${counts.implemented} · partial ${counts.partial} · deferred ${counts.deferred} · unmapped ${unmapped.length}

| Module | Planning dir | Owner | Code | Tests | Status |
|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(join(root, 'TRACEABILITY.md'), md);
console.log(`traceability: ${modules.length} modules, implemented ${counts.implemented}, partial ${counts.partial}, deferred ${counts.deferred}, unmapped ${unmapped.length}, problems ${problems.length}`);
if (problems.length) {
  console.error(problems.slice(0, 200).join('\n'));
  if (check) process.exit(1);
}
